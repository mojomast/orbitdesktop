// Dev tool: parse the part manifests into the rig tables rig.js consumes.
// Keeping these generated means art updates carry into the rig with no hand-copying.
//
//   node tools/gen_enemy_rigs.mjs              (writes the live files below)
//   node tools/gen_enemy_rigs.mjs --out DIR    (dry run: writes DIR/enemy-rigs.js + DIR/hero-rigs.js;
//                                              diff against live first - check-rigsync.mjs does this)
//
// Reads  assets/enemies/MANIFEST.md  -> pizza-panic/enemy-rigs.js   (export ENEMY_RIGS)
// Reads  assets/heroes/MANIFEST.md   -> pizza-panic/hero-rigs.js    (export HERO_RIGS)
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.resolve(here, '..', '..', 'pizza-panic');
// mr_india (t_7abe3a5269614640): --out DIR sends the output somewhere safe instead of over the live tables.
const outArg = process.argv.indexOf('--out');
const outDir = outArg > 0 && process.argv[outArg + 1] ? path.resolve(process.argv[outArg + 1]) : root;

// "## brawler (Brawler)" starts a type; table rows carry the parts.
function parse(file) {
  const manifest = fs.readFileSync(path.join(root, file), 'utf8');
  const types = [];
  let current = null;
  for (const line of manifest.split('\n')) {
    const head = line.match(/^##\s+(\w+)\s+\((.+)\)/);
    if (head) { current = { kind: head[1], title: head[2], parts: [], moves: '', behavior: '' }; types.push(current); continue; }
    if (!current) continue;
    const moveLine = line.match(/Mov[^:]*:\s*(.+)/);
    if (moveLine) current.moves = moveLine[1].trim();
    // mr_india (t_0309973138084dd1): "Weapon grip: N" = degrees the weapon art is turned in the fist so its
    // long axis sits in a natural grip under the shared poses (vertical katana/axe art vs horizontal staff/bat).
    const grip = line.match(/^Weapon grip:\s*(-?\d+)/);
    if (grip) current.grip = +grip[1];
    const behave = line.match(/Behavior:\s*(.+)/);
    if (behave) current.behavior = behave[1].trim();
    // Root rows use "-" for parent and "-" for attach; other rows use "a,b".
    const row = line.match(/^\|\s*(\w+)\s*\|\s*([\w.]+)\s*\|\s*(\d+)x(\d+)\s*\|\s*(\d+),(\d+)\s*\|\s*([\w-]+)\s*\|\s*(?:(\d+),(\d+)|-)\s*\|/);
    if (!row) continue;
    const [, part, image, w, h, px, py, parent, ax, ay] = row;
    current.parts.push({ part, image, w: +w, h: +h, px: +px, py: +py, parent: parent === '-' ? null : parent, ax: +(ax || 0), ay: +(ay || 0) });
  }
  if (!types.length) throw new Error(`no types found in ${file}`);
  return types;
}

function emit({ types, exportName, dest, source, skip = [] }) {
  const out = [];
  out.push(`// GENERATED by tools/gen_enemy_rigs.mjs from ${source}.`);
  out.push('// Do not hand-edit: re-run the generator after the art or manifest changes.');
  out.push('// Back limbs are not listed in the manifest, so they are derived here: the same');
  out.push("// image darkened with a small inward offset, matching MR.INDIA's convention.");
  out.push('');
  out.push(`export const ${exportName} = {`);
  const names = [];
  for (const t of types) {
    if (skip.includes(t.kind)) continue;
    names.push(t.kind);
    if (t.behavior) out.push(`  // ${t.title}: ${t.behavior}`);
    if (t.moves) out.push(`  // moves: ${t.moves}`);
    out.push(`  ${t.kind}: {`);
    for (const p of t.parts) {
      const parent = p.parent ? `'${p.parent}'` : 'null';
      const grip = p.part === 'weapon' && t.grip ? `, grip: ${t.grip}` : '';
      out.push(`    ${p.part}: { file: '${p.image}', w: ${p.w}, h: ${p.h}, px: ${p.px}, py: ${p.py}, parent: ${parent}, ax: ${p.ax}, ay: ${p.ay}${grip} },`);
    }
    // Derived back limbs (front limb image, drawn first and darkened).
    for (const [back, front] of [['uarm_b', 'uarm'], ['farm_b', 'farm'], ['thigh_b', 'thigh'], ['shin_b', 'shin']]) {
      const f = t.parts.find(p => p.part === front);
      if (!f) continue;
      const parent = back.startsWith('uarm') ? 'torso' : back.startsWith('farm') ? 'uarm_b' : back.startsWith('thigh') ? 'torso' : 'thigh_b';
      // Iteration 8 (MR.INDIA): only the shoulder/hip of a back limb is nudged inward;
      // the elbow/knee must match the front limb exactly or the joint opens a gap.
      const root = parent === 'torso';
      out.push(`    ${back}: { file: '${f.image}', w: ${f.w}, h: ${f.h}, px: ${f.px}, py: ${f.py}, parent: '${parent}', ax: ${root ? Math.max(2, f.ax - 6) : f.ax}, ay: ${root ? f.ay - 2 : f.ay}, back: true },`);
    }
    out.push('  },');
  }
  out.push('};');
  out.push('');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, dest), out.join('\n'));
  const summary = names.map(k => `${k}(${types.find(t => t.kind === k).parts.length})`).join(', ');
  console.log(`wrote ${path.join(outDir, dest)}: ${summary}`);
}

emit({
  types: parse('assets/enemies/MANIFEST.md'),
  exportName: 'ENEMY_RIGS',
  dest: 'enemy-rigs.js',
  source: 'assets/enemies/MANIFEST.md',
});

// Iteration 8: turtle_purple now has its own sheet and manifest section.
